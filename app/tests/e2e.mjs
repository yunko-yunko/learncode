import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const output = path.join(root,'test-results');
await fs.mkdir(output,{recursive:true});
const testData = path.join(root,'.test-data',`e2e-${Date.now()}`);
const env = {...process.env,LEARNCODE_TEST:'1',LEARNCODE_TEST_DATA:testData}; delete env.ELECTRON_RUN_AS_NODE;
const executablePath = process.env.LEARNCODE_EXECUTABLE;
const app = await electron.launch({executablePath,args:executablePath ? [] : [root],env,timeout:30000});
const errors = [];
try {
  const page = await app.firstWindow();
  const capture = async (filename) => { if (!executablePath) await page.screenshot({path:path.join(output,filename)}); };
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(message.type() === 'error') errors.push(message.text());});
  await page.waitForSelector('.course-card');
  assert.equal(await page.locator('.course-card').count(),3);
  assert.equal(await page.locator('.main-sidebar, .brand').count(),0);
  assert.equal(await page.locator('.learning-stats, .learning-hero, #course-search, [data-bookmark]').count(),0);
  await capture('01-library.png');
  await page.locator('[data-action="theme"]').click();
  await page.waitForFunction(()=>document.documentElement.dataset.theme === 'dark');
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  await capture('02-dark.png');
  await page.locator('[data-action="theme"]').click();
  await page.waitForFunction(()=>document.documentElement.dataset.theme === 'light');
  await page.locator('[data-open-course="fastapi-first-steps"]').first().click();
  await page.waitForSelector('#python-editor .cm-content');
  await capture('03-reader.png');
  assert.equal(await page.locator('#lesson-content .code-block').count(),2);
  await page.locator('[data-action="run-code"]').click();
  await page.waitForFunction(()=>document.querySelector('#runtime-state-text')?.textContent.includes('실행 중'),{},{timeout:30000});
  const firstResponse = await fetch('http://127.0.0.1:8083/');
  assert.equal(firstResponse.status,200); assert.equal((await firstResponse.json()).message,'Hello, learncode!');
  await capture('04-api-running.png');
  await page.locator('[data-action="add-file"]').click();
  await page.locator('#prompt-value').fill('routers/test.py'); await page.locator('#confirm-prompt').click();
  await page.waitForSelector('[data-file="routers/test.py"]');
  assert.equal(await page.locator('.tree-folder').count(),1);
  await page.locator('[data-action="complete-lesson"]').click();
  await page.waitForFunction(()=>document.querySelector('.sidebar-progress strong')?.textContent === '25%');
  await page.locator('[data-lesson="split-files"]').click();
  await page.waitForFunction(()=>document.querySelector('#lesson-content')?.textContent.includes('라우터를 연결'));
  await page.locator('[data-action="run-code"]').click();
  await page.waitForFunction(()=>document.querySelector('#runtime-state-text')?.textContent.includes('실행 중'),{},{timeout:30000});
  const multiResponse = await fetch('http://127.0.0.1:8083/items/7');
  assert.equal(multiResponse.status,200); assert.equal((await multiResponse.json()).name,'item-7');
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(560,800));
  await page.waitForTimeout(250);
  await capture('05-reader-small.png');
  assert.equal(await page.locator('.mobile-panel-tabs').isVisible(),true);
  await page.locator('[data-reader-panel="practice"]').click(); assert.equal(await page.locator('.practice-pane').isVisible(),true);
  await capture('06-practice-small.png');
  await page.locator('[data-action="home"]').click(); await page.waitForSelector('.course-card');
  await capture('07-library-small.png');
  assert.equal(await page.locator('.course-grid').evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' ').length),1);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > window.innerWidth),false);
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1440,960));
  await page.locator('[data-action="create"]').click(); await page.waitForSelector('#markdown-editor');
  await page.locator('#course-title').fill('테스트 강의'); await page.locator('#lesson-title').fill('첫 강좌');
  await page.locator('[data-action="add-lesson"]').click(); await page.locator('#lesson-title').fill('두 번째 강좌');
  await capture('08-creator.png');
  await page.locator('[data-format="table"]').click(); await page.waitForTimeout(250);
  assert.ok((await page.locator('#markdown-editor .cm-content').innerText()).includes('| 제목 | 설명 |'));
  await page.locator('#format-font').selectOption('Georgia');
  await page.locator('#format-size').selectOption('24');
  await page.waitForTimeout(250);
  assert.ok(await page.locator('#markdown-preview span[style*="font-family"]').count());
  assert.ok(await page.locator('#markdown-preview span[style*="font-size:24px"]').count());
  const downloadPath = path.join(output,'테스트 강의.zip');
  await app.evaluate(({dialog},file)=>{dialog.showSaveDialog = async ()=>({canceled:false,filePath:file});},downloadPath);
  await page.locator('[data-action="download-course"]').click();
  await page.waitForFunction(()=>document.querySelector('#toasts')?.textContent.includes('ZIP으로 저장'));
  const AdmZip = (await import('adm-zip')).default;
  const zip = new AdmZip(downloadPath); assert.equal(zip.getEntries().length,2);
  assert.match(zip.getEntries()[0].entryName,/테스트 강의\/테스트 강의_1강\.json/);
  await page.locator('[data-action="save-course"]').click(); await page.waitForFunction(()=>document.querySelector('#toasts')?.textContent.includes('강의를 저장'));
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(560,800));
  await page.waitForTimeout(250); await capture('09-creator-small.png');
  assert.equal(await page.locator('[data-action="download-course"]').isVisible(),true);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > window.innerWidth),false);
  await page.locator('[data-action="home"]').click(); await page.waitForSelector('.course-card');
  assert.equal(await page.locator('.course-card').count(),4);
  for (const width of [420,768,1024]) {
    await app.evaluate(({BrowserWindow},width)=>BrowserWindow.getAllWindows()[0].setSize(width,800),width);
    await page.waitForTimeout(150);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > window.innerWidth),false);
    await capture(`library-${width}.png`);
  }
  await app.evaluate(({dialog},file)=>{dialog.showOpenDialog = async ()=>({canceled:false,filePaths:[file]});},downloadPath);
  await page.locator('.floating-add').click(); await page.locator('[data-import="file"]').click();
  await page.waitForFunction(()=>document.querySelectorAll('.course-card').length === 5);
  assert.deepEqual(errors,[]);
  await page.locator('[data-open-course="fastapi-first-steps"]').first().click();
  await page.waitForSelector('#python-editor .cm-content');
  await page.locator('#python-editor .cm-content').fill('# saved on window close\n');
  const appClosed = app.waitForEvent('close');
  await page.evaluate(()=>window.learncode.windowControl('close'));
  await appClosed;
  const savedState = JSON.parse(await fs.readFile(path.join(testData,'learning-state.json'),'utf8'));
  assert.ok(Object.values(savedState.workspaces).some(workspace=>Object.values(workspace.files).includes('# saved on window close\n')));
  console.log('PASS: 최소 화면 구성, 테마, 실제 FastAPI, 다중 파일, 진도, 420~1440px 반응형, 강의 작성, ZIP 다운로드·가져오기, 종료 직전 저장');
  console.log(`스크린샷: ${output}`);
} finally { await app.close().catch(()=>{}); }
